#!/usr/bin/env python3
"""Deploy SuccessBrian OS tracked-link redirects.

Source of truth: campaignsdesk.outbound_links (active rows). Renders
/etc/nginx/snippets/sbos-links.conf on gamma (successbrianvps.com):
one exact-match location per slug, 302 to the target, hits logged to
/var/log/nginx/sbos-clicks.log (ingested by linktrack_ingest.py).
Unknown/inactive slugs get 404, never the SPA shell.

The generated file has carried a "run link_tracking.py deploy" header
since 2026-10-28, but the tool itself was never saved to the repo -
rebuilt 2026-10-29 (Spencer) in the exact format it replaces.

Usage:
  python3 link_tracking.py render          # print the conf to stdout
  python3 link_tracking.py deploy          # render, ship, nginx -t, reload
"""
import subprocess
import sys

GAMMA = "root@100.118.196.66"
REMOTE_CONF = "/etc/nginx/snippets/sbos-links.conf"

HEADER = """# sbos-links.conf - GENERATED by CampaignsDesk link_tracking.py
# Source of truth: campaignsdesk.outbound_links (active rows).
# Do not hand-edit; run link_tracking.py deploy.
"""


def render():
    sys.path.insert(0, "/home/successbrian/successbrian-os/tools/pm")
    import pm_core
    conn = pm_core.conn()
    with conn.cursor() as cur:
        cur.execute("select slug, target_url from campaignsdesk.outbound_links "
                    "where active order by slug")
        rows = cur.fetchall()
    out = [HEADER]
    for slug, target in rows:
        out.append("location = /v/%s {\n"
                   "    access_log /var/log/nginx/sbos-clicks.log sbos_clicks;\n"
                   "    return 302 %s;\n"
                   "}\n" % (slug, target))
    out.append("# Unknown or inactive slugs: 404, never the SPA shell.\n"
               "location /v/ {\n"
               "    access_log /var/log/nginx/sbos-clicks.log sbos_clicks;\n"
               "    return 404;\n"
               "}\n")
    return "".join(out), len(rows)


def ssh(cmd, **kw):
    return subprocess.run(["ssh", "-o", "ConnectTimeout=10", GAMMA, cmd],
                          capture_output=True, text=True, timeout=90, **kw)


def deploy():
    conf, n = render()
    r = subprocess.run(["scp", "-o", "ConnectTimeout=10", "/dev/stdin",
                        "%s:/tmp/sbos-links.conf" % GAMMA],
                       input=conf, capture_output=True, text=True, timeout=90)
    if r.returncode != 0:
        raise SystemExit("scp failed: " + r.stderr)
    r = ssh("cp %s %s.bak-auto && cp /tmp/sbos-links.conf %s && "
            "nginx -t && nginx -s reload" % (REMOTE_CONF, REMOTE_CONF,
                                             REMOTE_CONF))
    if r.returncode != 0:
        raise SystemExit("remote deploy failed: " + (r.stderr or r.stdout))
    print("link_tracking deploy: %d active slugs live" % n)


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "deploy":
        deploy()
    else:
        conf, n = render()
        print(conf)
        print("# %d active slugs" % n, file=sys.stderr)
